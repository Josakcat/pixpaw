if __name__ == "__main__":
    import re
    from pathlib import Path
    import sprites
    src = Path(__file__).resolve().parent.parent / "Sources" / "Pixpaw"

    # Art that was 3 pt a pixel doubles; art that was 2 pt (over the head, the agent's) goes 4 / 3.
    TWO_PT = {"heart", "zzz", "fish", "note", "code", "sweat", "dizzy1", "dizzy2", "dizzy3",
              "popcorn", "hourglass", "cobweb", "confetti", "rainCloud", "parcel", "rock", "paper", "scissors"}

    def check(name, rows, old_w, old_h, letters, two_pt=False):
        want_w, want_h = (round(old_w * 4 / 3), round(old_h * 4 / 3)) if two_pt else (2 * old_w, 2 * old_h)
        assert len(rows) == want_h, f"{name}: {len(rows)} rows, want {want_h}"
        assert all(len(r) == want_w for r in rows), f"{name}: rows not {want_w} wide"
        missing = {c for r in rows for c in r} - set(letters) - {"."}
        assert not missing, f"{name}: no colour for {missing}"

    for name, old in sprites.ACCESSORIES.items():
        assert name in FINE_ACCESSORIES, f"missing accessory {name}"
    acc = {**sprites.ACCESSORY_COLORS, **FINE_ACCESSORY_COLORS}
    for name, rows in FINE_ACCESSORIES.items():
        old = sprites.ACCESSORIES[name]
        check(name, rows, len(old[0]), len(old), acc)
    eff = {**sprites.EFFECT_COLORS, **FINE_EFFECT_COLORS}
    for name, rows in FINE_EFFECTS.items():
        old = sprites.EFFECTS[name]
        check(name, rows, len(old[0]), len(old), eff, name in TWO_PT)

    toys = (src / "ToyArt.swift").read_text()
    old_toys = {m.group(1): re.findall(r'"([^"]*)"', m.group(2))
                for m in re.finditer(r'\.(\w+): \(\[\n((?:\s+"[^"]*",\n)+)', toys)}
    assert set(old_toys) == set(FINE_TOYS), f"toys differ: {set(old_toys) ^ set(FINE_TOYS)}"
    for name, (rows, pal) in FINE_TOYS.items():
        check(name, rows, len(old_toys[name][0]), len(old_toys[name]), set(pal) | {"o"})

    agent = (src / "AgentArt.swift").read_text()
    for name, (frames, pal) in FINE_AGENT.items():
        body = re.search(r"case \." + name + r":\n(?:\s+//[^\n]*\n)*\s+return \(\[(.*?)\]\], \[", agent, re.S).group(1)
        old_frames = [re.findall(r'"([^"]*)"', f) for f in re.findall(r"\[(.*?)\]", body + "]", re.S)]
        old_frames = [f for f in old_frames if f]
        assert len(frames) == len(old_frames), f"{name}: {len(frames)} frames, want {len(old_frames)}"
        for f, old in zip(frames, old_frames):
            check(name, f, len(old[0]), len(old), set(pal) | {"o"}, name in TWO_PT)
    assert set(FINE_HOMES) == set(sprites.HOMES), f"homes differ: {set(FINE_HOMES) ^ set(sprites.HOMES)}"
    homes = {**sprites.HOME_COLORS, **FINE_HOME_COLORS}
    assert not set(FINE_HOME_COLORS) & set(sprites.HOME_COLORS), "a home shade reuses an old letter"
    for name, rows in FINE_HOMES.items():
        check(name, rows, sprites.HOME_W, sprites.HOME_H, homes)
        # the doorway opens by its letter: it has to be there, where the old one was
        old_d = {(x, y) for y, r in enumerate(sprites.HOMES[name]) for x, c in enumerate(r) if c == "d"}
        new_d = {(x // 2, y // 2) for y, r in enumerate(rows) for x, c in enumerate(r) if c == "d"}
        assert new_d <= old_d and len(new_d) >= len(old_d) * 0.8, f"{name}: doorway moved"
    assert not set(FINE_EFFECT_COLORS) & set(sprites.EFFECT_COLORS) - {"o"}, "an effect shade reuses an old letter"
    assert set(FINE_DECOR) == set(sprites.DECOR), f"decor differs: {set(FINE_DECOR) ^ set(sprites.DECOR)}"
    for name, rows in FINE_DECOR.items():
        old = sprites.DECOR[name]
        check(name, rows, len(old[0]), len(old), homes)
    print("fine_extras: ok,", len(FINE_HOMES), "homes,", len(FINE_ACCESSORIES), "accessories,", len(FINE_EFFECTS), "effects,",
          len(FINE_TOYS), "toys,", len(FINE_AGENT), "agent pictures,", len(FINE_DECOR), "decorations")
